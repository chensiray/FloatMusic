"""Generate the native catalog from the same source as the Qt UI.

Run with --missing to audit Android-specific literals. No third-party packages.
"""
import pathlib, re, json, sys, hashlib
root=pathlib.Path(__file__).resolve().parent.parent
catalog=(root/'src/uilanguage_en.inc').read_text(encoding='utf-8')
entry=re.compile(r'\{QStringLiteral\(("(?:\\.|[^"\\])*")\), QStringLiteral\(("(?:\\.|[^"\\])*")\)\}')
entries={json.loads(a):json.loads(b) for a,b in entry.findall(catalog)}
token=re.compile(r'//[^\n]*|/\*[\s\S]*?\*/|"(?:\\.|[^"\\])*"|\'(?:\\.|[^\'\\])*\'')
if '--missing' in sys.argv:
    missing=set()
    paths=list((root/'android/src/org/floatmusic/player').glob('*.java'))+[root/'qml/AndroidMain.qml']
    for path in paths:
        for match in token.finditer(path.read_text(encoding='utf-8')):
            if match.group().startswith('"') and re.search(r'[\u4e00-\u9fff]',match.group()):
                text=json.loads(match.group())
                if text not in entries: missing.add(text)
    out=root/'artifacts/v1.4-android-preview-2026-10-20/android-strings-missing.json'
    out.write_text(json.dumps(sorted(missing),ensure_ascii=False,indent=2),encoding='utf-8'); print(len(missing));sys.exit()
lines=['package org.floatmusic.player;','', '// Generated by scripts/sync-android-translations.py from src/uilanguage_en.inc.',
       'final class UiCatalog {', '    static final java.util.Map<String,String> EN = new java.util.LinkedHashMap<>();',
       '    static {']
for source,value in entries.items():
    lines.append('        EN.put(%s,%s);'%(json.dumps(source,ensure_ascii=False),json.dumps(value,ensure_ascii=False)))
lines+=['    }','}']
(root/'android/src/org/floatmusic/player/UiCatalog.java').write_text('\n'.join(lines)+'\n',encoding='utf-8')
print('Generated',len(entries),'shared translations')
